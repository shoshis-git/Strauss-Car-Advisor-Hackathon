@pytest.mark.parametrize("pdf", [E004_PDF, LOGICAL_PDF], ids=["visual", "logical"])
def test_identifying_details_are_masked(pdf):
    text = redact(read_pdf_text(pdf))
    for secret in PRIVATE:
        assert secret not in text, secret
    # pay data survives (incl. 'נקודות זיכוי', which a naive ת.ז pattern would hit)
    assert "שכר בסיס" in text and "נקודות זיכוי" in text


def test_redaction_masks_glued_and_unlabelled_identifiers():
    assert redact("7654321חשבון  600סניף") == "[הושחר]"
    assert redact("ת.ז 012345678") == "[הושחר]"
    assert "[הושחר]" in redact("פרטים 0521234567") and "0521234567" not in redact("פרטים 0521234567")
    assert redact("a@b.co שכר בסיס 9,000") == "[הושחר] שכר בסיס 9,000"
    assert redact("שכר בסיס 16,000.00") == "שכר בסיס 16,000.00"   # money is not an ID


def test_model_never_receives_identifying_details():
    llm = CapturingLLM({"base_salary": 16000})
    extract_payslip(E004_PDF, llm, CONFIG)
    sent = llm.sent[0]
    assert "16,000.00" in sent
    for secret in PRIVATE:
        assert secret not in sent, secret


