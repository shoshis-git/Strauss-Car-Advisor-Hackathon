"""Payslip upload: PDF text, redaction, extraction, verification, API.

Fixtures are synthetic (fictional people), generated by fixtures/make_payslips.py.
payslip_e004.pdf carries the pay data of sample employee E-004, so a payslip-driven
conversation must reproduce the Excel reference numbers."""
from __future__ import annotations

import io
from pathlib import Path

import pytest
from fastapi.testclient import TestClient

from backend.agent.llm import LLMStep, ToolCall, assistant_message
from backend.agent.payslip import (MAX_BYTES, PayslipError, extract_payslip, llm_extract,
                                   read_pdf_text, redact, rule_based_extract, verify)
from backend.agent.rule_based import RuleBasedLLM
from backend.data_loader.config_loader import get_config
from backend.main import create_app

CONFIG = get_config()
FIXTURES = Path(__file__).parent / "fixtures"
E004_PDF = (FIXTURES / "payslip_e004.pdf").read_bytes()
LOGICAL_PDF = (FIXTURES / "payslip_logical.pdf").read_bytes()
SCANNED_PDF = (FIXTURES / "payslip_scanned.pdf").read_bytes()
# identifying details printed on both fixtures - must never pass redaction
PRIVATE = ["123456782", "7654321", "1234567", "050", "ישראלי", "הרצל", "תל אביב"]
PDF = {"Content-Type": "application/pdf"}


def values(extraction) -> dict:
    return {f.field: f.value for f in extraction.fields}


class CapturingLLM:
    """A 'real' model stand-in: records what it was sent, answers with a fixed tool call."""

    def __init__(self, args: dict):
        self.args, self.sent = args, []

    def step(self, *, system, messages, tools, state):
        self.sent.append("\n".join(m["content"] for m in messages))  # the payslip content
        call = ToolCall("p1", tools[0]["name"], self.args)
        return LLMStep("", [call], assistant_message("", [call]))


