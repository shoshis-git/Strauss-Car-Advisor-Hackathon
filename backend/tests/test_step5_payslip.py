def test_e004_payslip_is_fully_extracted():
    ex = extract_payslip(E004_PDF, RuleBasedLLM(CONFIG), CONFIG)
    assert values(ex) == {"occupation": "מנהל/ת אזור מכירות", "base_salary": 16000,
                          "commissions_bonuses": 3000, "pension_pct": 6, "hishtalmut_pct": 2.5,
                          "credit_points": 2.25, "current_participation": 400}
    assert ex.not_found == [] and ex.rejected == []
    ev = {f.field: f.evidence for f in ex.fields}
    assert "קופת גמל" in ev["pension_pct"] and "השתתפות" in ev["current_participation"]


def test_amount_only_pension_and_employer_lines_are_not_used():
    ex = extract_payslip(LOGICAL_PDF, RuleBasedLLM(CONFIG), CONFIG)
    v = values(ex)
    assert "pension_pct" not in v            # only an amount (852) - never computed
    assert v["commissions_bonuses"] == 3000  # 2,000 + 1,000 summed in code
    assert v["hishtalmut_pct"] == 2.5 and v["credit_points"] == 2.75
    assert "אחוז הפרשת עובד לפנסיה" in ex.not_found


def test_model_values_not_in_the_payslip_are_dropped():
    text = redact(read_pdf_text(E004_PDF))
    raw = {"base_salary": 17000,            # invented
           "commission_items": [3000],
           "pension_pct": 6.5,              # wrong
           "credit_points": 2.25,
           "car_participation": 4790,       # the value of use, out of the field's range? no:
           "evidence": {"credit_points": "שורה מומצאת"}}
    ex = verify(raw, text, CONFIG)
    v = values(ex)
    assert "base_salary" not in v and "pension_pct" not in v
    assert v["credit_points"] == 2.25        # real value; the true line replaces a fake quote
    assert next(f for f in ex.fields if f.field == "credit_points").evidence.endswith("נקודות זיכוי")
    assert any("17000" in r for r in ex.rejected) and any("6.5" in r for r in ex.rejected)


def test_model_cannot_sum_commissions_itself():
    text = redact(read_pdf_text(LOGICAL_PDF))
    ex = verify({"commission_items": [3000]}, text, CONFIG)  # 2,000 + 1,000 done by the model
    assert "commissions_bonuses" not in values(ex)


def test_out_of_range_and_unknown_occupation_are_rejected():
    text = "שכר בסיס 500\nתפקיד: אסטרונאוט\nנקודות זיכוי 2.25"
    ex = verify({"base_salary": 500, "occupation": "אסטרונאוט", "credit_points": 2.25},
                text, CONFIG)
    assert values(ex) == {"credit_points": 2.25}
    assert any("לא סביר" in r for r in ex.rejected)
    assert any("אינו בטבלת העיסוקים" in r for r in ex.rejected)


def test_llm_answer_without_tool_call_is_parsed_or_ignored():
    class TextLLM:
        def __init__(self, text):
            self.text = text

        def step(self, **kw):
            return LLMStep(self.text, [], assistant_message(self.text, []))

    assert llm_extract("x", TextLLM('{"base_salary": 16000}')) == {"base_salary": 16000}
    assert llm_extract("x", TextLLM("לא מצאתי")) == {}


def test_rule_based_extractor_reads_percent_next_to_its_sign():
    out = rule_based_extract("1,140.00 %6.00 קופת גמל - חלק עובד")
    assert out["pension_pct"] == 6.0


