@pytest.mark.parametrize("data, status, words", [
    (SCANNED_PDF, 422, "צילום או סריקה"),
    (b"GIF89a....", 415, "PDF"),
    (b"%PDF-1.7 garbage", 422, "פגום"),
    (b"%PDF-" + b"0" * MAX_BYTES, 413, "גדול"),
], ids=["scanned", "not-pdf", "corrupt", "too-big"])
def test_bad_files_are_rejected_with_a_reason(data, status, words):
    with pytest.raises(PayslipError) as e:
        read_pdf_text(data)
    assert e.value.status == status and words in str(e.value)


def test_glyph_code_text_layer_is_reported_as_unreadable():
    """A real payroll PDF (ט.מ.ל) stored glyph codes, not characters: say so honestly."""
    data = (FIXTURES / "payslip_glyph_codes.pdf").read_bytes()
    with pytest.raises(PayslipError, match="קידוד פנימי של הגופן") as e:
        read_pdf_text(data)
    assert e.value.status == 422


def test_base_salary_synonym():
    assert rule_based_extract("355.00 45.00 7.88 שכר יסוד")["base_salary"] == 355


def test_password_protected_pdf_is_rejected():
    from pypdf import PdfReader, PdfWriter
    w = PdfWriter(clone_from=PdfReader(io.BytesIO(E004_PDF)))
    w.encrypt("secret")
    buf = io.BytesIO()
    w.write(buf)
    with pytest.raises(PayslipError, match="סיסמה"):
        read_pdf_text(buf.getvalue())


