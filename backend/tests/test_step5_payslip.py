def test_visual_order_hebrew_is_restored():
    text = read_pdf_text(E004_PDF)  # stored reversed, as many payroll systems do
    assert "שכר בסיס" in text and "16,000.00" in text and "נקודות זיכוי" in text
    assert "סיסב רכש" not in text


